import pandas as pd

def create_features(df):
    """
    Generate time-series features for energy consumption prediction.
    Assumes df has 'Date' and 'Total Consumption'
    """
    df = df.copy()
    if 'Date' not in df.columns and df.index.name != 'Date':
        raise ValueError("DataFrame must have a 'Date' column or index.")
        
    if 'Date' in df.columns:
        df['Date'] = pd.to_datetime(df['Date'])
        df.set_index('Date', inplace=True)
    
    # Ensure it's sorted
    df.sort_index(inplace=True)
    
    # Date-based features
    df['DayOfWeek'] = df.index.dayofweek
    df['DayOfMonth'] = df.index.day
    df['Month'] = df.index.month
    df['IsWeekend'] = df['DayOfWeek'].apply(lambda x: 1 if x >= 5 else 0)
    
    # Lag features
    df['Lag_1'] = df['Total Consumption'].shift(1)
    df['Lag_7'] = df['Total Consumption'].shift(7)
    
    # Rolling averages (using past values only, so shift then roll or roll then shift)
    df['Rolling_Mean_3'] = df['Total Consumption'].shift(1).rolling(window=3).mean()
    df['Rolling_Mean_7'] = df['Total Consumption'].shift(1).rolling(window=7).mean()
    
    # Drop NaNs generated by shifting
    df.dropna(inplace=True)
    
    return df
